export function buildCodexCommitPrompt(repository: {
  name: string
  path: string
}) {
  return [
    '【Git 提交任务】',
    `项目：${repository.name}`,
    `仓库路径：${repository.path}`,
    '',
    '这是一个独立的本地提交流程。不要进行 Bug 检测，不要判断改动对应哪个 Bug、问题单或历史任务，也不要以“与当前任务无关”为理由停止提交。',
    '1. 先检查当前分支、工作区状态和实际 diff；如果存在未解决的合并冲突，停止并说明冲突文件。',
    '2. 不得因为同时存在多个功能、多个 Bug 范围的改动、无法追溯改动所属任务或工作区不干净而停止提交。',
    '3. 只排除已确认包含明文密码、令牌、私钥等敏感凭据的文件，或明确属于缓存、临时文件且不应入库的产物。不要仅凭文件名、目录名、“环境配置”字样或 Bug 编号猜测并排除文件。',
    '4. 暂存所有剩余的当前改动，包括看起来与本会话无关的功能改动或已跟踪的环境配置文件；然后创建一次本地提交。',
    '5. 根据实际 diff 和最近提交记录理解仓库的 commit message 规范，自行生成简洁、准确、可追溯的提交说明；不要照抄本提示词，也不要询问用户提交说明。',
    '6. 不要 push、merge、rebase、amend、重置或切换分支。',
    '7. 完成后报告提交哈希、采用的提交说明、变更文件和验证结果。如果排除过文件，只说明确认过的排除原因。',
  ].join('\n')
}
